from datetime import datetime, timedelta
from math import pi
import os
import warnings

import numpy as np
from skyfield.api import EarthSatellite, load

from object_definitions.Constants_def import Constants
from object_definitions.Orbit_def import Orbit_specification
from object_definitions.ReadWriteSatData import ReadWriteSatData


class Satellite:
    """One satellite, wrapping a Skyfield ``EarthSatellite`` for propagation.

    Initialise with **either** an :class:`~object_definitions.Orbit_def.Orbit_specification` (a TLE is then
    auto-generated under the autogenerated folder) **or** a TLE file path. After the
    constellation sets the timescale, the propagation methods fill the ECI position/velocity arrays the
    rest of the simulator reads.

    Attributes
    ----------
    skf : skyfield.sgp4lib.EarthSatellite
        The Skyfield satellite used to propagate.
    positions_eci, velocities_eci : numpy.ndarray
        Propagated ECI state ``(3, n)`` [m, m/s], filled by the propagate methods.
    time_prop_vec : list
        Timestamps of the propagated state.
    tle_file_path : str or None
        Path to the (auto-generated or supplied) TLE file.
    """

    def __init__(
        self,
        satID,
        orbit_n=None,
        satName=None,
        tle_file_path=None,
        satNo_in_tle=0,
        rx_antenna=None,
        battery=None,
        solarArray=None,
        verbose=False,
    ):
        """Initialise from an Orbit_specification or a TLE file (never both); load ephemeris data.

        Parameters
        ----------
        satID : int
            Unique identifier for the satellite.
        orbit_n : Orbit_specification or list, optional
            Orbit specification (or a 6/7-element parameter list). Mutually exclusive with ``tle_file_path``.
        satName : str, optional
            Satellite name.
        tle_file_path : str, optional
            Path to a TLE file. Mutually exclusive with ``orbit_n``.
        satNo_in_tle : int, optional
            Index of the satellite in the TLE file (default 0; TLE init only).
        rx_antenna : RxAntenna, optional
            GNSS-R receiver antenna (not used for coverage).
        battery, solarArray : object, optional
            Reserved for future power modelling.
        verbose : bool, optional
            Print initialisation progress.
        """
        # If tle-file is provided, initialize the satellite with the TLE data
        if tle_file_path is not None:
            if not os.path.exists(tle_file_path):
                raise FileNotFoundError(f"TLE file not found: {tle_file_path}")
            if orbit_n is not None:
                raise ValueError("Cannot initialize Satellite with both TLE file and Orbit_specification object")
            if verbose:
                print(f"Initializing Satellite with TLE file: {tle_file_path}")
            self._init_with_TLE(tle_file_path, satNo_in_tle, satName)
        else:
            # Initialize satellite with Orbit_specification object
            if verbose:
                print("Initializing Satellite with Orbit_specification object")
            self._initWithOrbit(satID, orbit_n, satName)

        # Load
        file_path = os.path.join(Constants.skyfield_data, "de421.bsp")
        self.planets = load(file_path)  # TODO move to constants
        # earth   = planets['earth']
        # sun     = planets['sun']

        self.gnss_r_antenna = rx_antenna if rx_antenna is not None else None
        self.battery = battery if battery is not None else None  # TODO: Battery object to be implemented
        self.solarArray = solarArray if solarArray is not None else None  # TODO: SolarArray object to be implemented
        self.tle_str = None
        self.times_skyfield = None
        self.sunlit_count = None
        self.sunlit_fraction = None

    """
    =========================================================================================================
    Setter functions
    =========================================================================================================
    """

    def set_timescale_simulation(self, timeSkyfield) -> None:
        """
        =========================================================================================================
        Set the Skyfield timescale for the simulation.

        INPUTS:
            timeSkyfield: [skyfield.timelib.Time]   Skyfield timescale array
        =========================================================================================================
        """
        if timeSkyfield is None:
            raise ValueError("Invalid timescale object provided")
        self.times_skyfield = timeSkyfield

    def set_classification(self, classification) -> None:
        """
        =========================================================================================================
        Set the classification of the satellite.

        INPUTS:
            classification: [str]   One of 'U' (unclassified), 'C' (classified), 'S' (secret)
        =========================================================================================================
        """
        if classification not in ["U", "C", "S"]:
            raise ValueError("Invalid classification")
        self.classification = classification

    def set_orbit(self, orbit_n) -> None:
        """
        =========================================================================================================
        Set the Orbit_specification of the satellite.

        INPUTS:
            orbit_n: [Orbit_specification | list]   Either an Orbit_specification, or a 6-element list
                                                    [inclination, eccentricity, raan, argPeriapsis, nu, a]
        =========================================================================================================
        """
        if isinstance(orbit_n, Orbit_specification):
            self.orbit_n = orbit_n
        elif isinstance(orbit_n, list):
            if len(orbit_n) == 6:
                # Orbit_specification is initialized with new orbital parameters
                self.orbit_n = Orbit_specification(*orbit_n)
            elif len(orbit_n) < 6:
                print(
                    "Insuffizient data to specify Orbit_specification of satellite: ",
                    self.satName,
                )
        else:
            raise ValueError(
                "Invalid Orbit_specification object provided for satellite: ",
                self.satName,
            )

    def set_epoch(self, epoch) -> None:
        """
        =========================================================================================================
        Set the epoch of the satellite. If a TLE has not been generated yet, it is generated here.

        INPUTS:
            epoch: [datetime]   UTC-aware datetime to use as the orbit epoch
        =========================================================================================================
        """
        if self.orbit_n is None:
            warnings.warn("Orbit_specification is not specified for this satellite. Cannot set epoch.", stacklevel=2)
            return
        self.orbit_n.set_start_time(epoch)

        # Generate TLE file if it does not exist and generate the skyfield satellite object
        if not self.tle_exists():
            self.write_tle_file()
            self.skf = load.tle_file(self.tle_file_path)[0]

    """
    =========================================================================================================
    Getter functions
    =========================================================================================================
    """

    def get_TLE(self) -> str:
        """
        =========================================================================================================
        Get the TLE file path if a TLE has been generated.

        OUTPUT:
            tle_file_path: [str | None]   Path to the satellite's TLE file, or None
        =========================================================================================================
        """
        if self.tle_exists():
            return self.tle_file_path
        else:
            warnings.warn("TLE has not yet been generated", stacklevel=2)
            return None

    def get_orbit(self) -> Orbit_specification:
        # Extract orbit_n from the satellit object
        return self.orbit_n

    def tle_exists(self) -> bool:
        """
        =========================================================================================================
        Check if a TLE file path has been registered for this satellite.

        OUTPUT:
            exists: [bool]   True if `self.tle_file_path` names an existing file
        =========================================================================================================
        """
        return self.tle_file_path is not None and os.path.isfile(self.tle_file_path)

    def write_tle_file(self) -> str:
        """
        =========================================================================================================
        Generate a TLE for this satellite and write it to a file under `Constants.tle_eph_folder_path`.
        The file path is stored in `self.tle_file_path`.

        OUTPUT:
            None: TLE path is stored in `self.tle_file_path`. Returns None on failure.
        =========================================================================================================
        """
        tle_str = ReadWriteSatData.generate_tle_data_string(self)
        if tle_str is None:
            print("TLE DATA CANNOT BE GENERATED FOR SATELLITE: ", self.satID)
            return None
        self.tle_str = tle_str

        # Make sure the directory exists
        if not os.path.exists(Constants.tle_eph_folder_path):
            print(f"Creating directory: {Constants.tle_eph_folder_path}")
            os.makedirs(Constants.tle_eph_folder_path)

        file_path = os.path.join(Constants.tle_eph_folder_path, self.satName + ".tle")
        with open(file_path, "w", encoding="ascii", newline="\n") as tle_file:
            tle_file.write(tle_str)
            tle_file.write("\n")
        self.tle_file_path = file_path
        return None

    def propagate_orbit(self, startTime, duration, deltaT) -> np.array:
        """
        =========================================================================================================
        Propagate the satellite orbit for a given duration and time step using Skyfield.

        Stores the propagated state in `self.time_prop_vec`, `self.positions_eci`,
        and `self.velocities_eci`.

        INPUTS:
            startTime: [datetime]   Start time of the propagation
            duration:  [int]        Duration of the propagation [seconds]
            deltaT:    [int]        Time step for the propagation [seconds]
        =========================================================================================================
        """
        times_i = []
        ts = load.timescale()
        for t in range(0, duration, deltaT):
            times_i.append(ts.utc(startTime + timedelta(seconds=t)))

        position = np.array([self.skf.at(t).position.m for t in times_i])
        velocity = np.array([self.skf.at(t).velocity.m_per_s for t in times_i])

        self.time_prop_vec = times_i
        self.positions_eci = np.transpose(position)
        self.velocities_eci = np.transpose(velocity)

    def propagate_orbit_for_times(self, times_skyfield) -> None:
        """
        =========================================================================================================
        Propagate the satellite at specific Skyfield times only.
        Much faster and memory-efficient for sparse timestamp sets (e.g., when GNSS positions are
        only needed at LEO-visible times).

        Stores the propagated state in `self.positions_eci`, `self.velocities_eci`,
        and `self.time_prop_vec`.

        INPUTS:
            times_skyfield: [skyfield.timelib.Time]   Time array to propagate at (non-empty)
        =========================================================================================================
        """
        if times_skyfield is None or len(times_skyfield) == 0:
            raise ValueError("times_skyfield must be a non-empty list of Skyfield times.")

        # Ensure we have a valid Skyfield satellite
        if not hasattr(self, "skf"):
            raise ValueError("Satellite Skyfield object (self.skf) not initialized.")

        # Compute ECI positions/velocities only at given timestamps
        pos = np.array([self.skf.at(t).position.m for t in times_skyfield])
        vel = np.array([self.skf.at(t).velocity.m_per_s for t in times_skyfield])

        self.positions_eci = pos.T
        self.velocities_eci = vel.T
        self.time_prop_vec = times_skyfield

    def calculate_sunlight_time(self) -> None:
        """
        =========================================================================================================
        Calculate when the satellite is in sunlight, populating `self.sunlit_count` (boolean array)
        and `self.sunlit_fraction`.
        =========================================================================================================
        """
        if self.times_skyfield is None:
            raise ValueError(
                "Simulation time not set for satellite    \n                => Call set_simulation_duration() in the SatConstellation class before calling this function or set_timescale_simulation() in the Satellite class"
            )
        self.sunlit_count = self.skf.at(self.times_skyfield).is_sunlit(self.planets)
        self.sunlit_fraction = np.sum(self.sunlit_count) / len(self.sunlit_count)

    def _init_with_TLE(self, tle_file_path, satNo_in_tle, satName=None):  # noqa: N802
        """
        =========================================================================================================
        Initialize the satellite object with TLE data from a file.

        INPUTS:
            tle_file_path: [str]         Path to the TLE file
            satNo_in_tle:  [int]         Index of the satellite in the TLE file
            satName:       [str | None]  Optional satellite name; if given, the matching entry is used
        =========================================================================================================
        """
        sat_data_all = ReadWriteSatData.read_tle_data(tle_file_path)
        if sat_data_all is None:
            raise ValueError("Invalid TLE data")

        if len(sat_data_all) > 1 and satName is None and satNo_in_tle == 0:
            print(
                "Warning: Multiple satellites found in TLE file. Using the first satellite data only.     \n    => If all satellites should be initialized, use the SatelliteConfiguration class"
            )

        if satName is not None:
            # Initialize one satellite from a TLE file only
            sat_data = None
            selected_index = None
            for index, sat_data_i in enumerate(sat_data_all):
                if sat_data_i.satName == satName:
                    sat_data = sat_data_i
                    selected_index = index
                    break
            if sat_data is None:
                raise ValueError(f"Satellite '{satName}' not found in TLE file")
        else:
            try:
                selected_index = int(satNo_in_tle)
            except (TypeError, ValueError) as exc:
                raise ValueError(f"satNo_in_tle must be an integer index; got {satNo_in_tle!r}") from exc
            if selected_index != satNo_in_tle or not (0 <= selected_index < len(sat_data_all)):
                raise IndexError(f"satNo_in_tle {satNo_in_tle!r} outside TLE file range [0, {len(sat_data_all) - 1}]")
            sat_data = sat_data_all[selected_index]

        # calculate semi major axis
        self.tle_file_path = tle_file_path
        self.satID = sat_data.satCatalogNumber
        self.satName = sat_data.satName
        self.classification = sat_data.classification
        semi_major_axis = (Constants.GM_EARTH_TT / (sat_data.meanMotion * 2 * pi / Constants.SEC_PER_DAY) ** 2) ** (1 / 3)
        true_anomaly = ReadWriteSatData.mean_to_true_anomaly_deg(sat_data.meanAnomaly, sat_data.eccentricity)  # Orbit_specification holds true anomaly
        self.orbit_n = Orbit_specification(
            sat_data.inclination,
            sat_data.eccentricity,
            sat_data.raan,
            sat_data.argOfPerigee,
            true_anomaly,
            semi_major_axis,
            sat_data.epoch,
        )
        self.launch_year = sat_data.launchYear
        self.lauch_Noyear = sat_data.lauchNoInYear
        self.lauch_piece = sat_data.launchPiece
        self.meanMotion_1 = sat_data.firstDerMeanMotion # balistic coefficient
        self.meanMotion_2 = sat_data.secDerivMeanMotion # mean motion second derivative
        self.B_star = sat_data.B_star
        self.element_set_no = sat_data.ElementSetNo
        skyfield_satellites = load.tle_file(tle_file_path)
        if selected_index >= len(skyfield_satellites):
            raise IndexError(f"Selected TLE index {selected_index} is absent from Skyfield's parsed records.")
        self.skf = skyfield_satellites[selected_index]

    def _initWithOrbit(self, satID, orbit_n, satName):  # noqa: N802
        # Initialize satellite object
        self.satID = satID
        self.satName = satName if satName is not None else f"Sat_{satID}"
        self.classification = "U"
        self.tle_file_path = None
        self.launch_year = int(datetime.now().year)
        self.lauch_Noyear = 1
        self.lauch_piece = "A"
        self.meanMotion_1 = None    # TODO calculate meanMotion1 (balistic coefficient) in a separate function
        self.meanMotion_2 = None    # TODO calculate meanMotion2 in a separate function
        self.B_star = None          # TODO calculate B_star in a separate function
        self.element_set_no = None  # TODO

        # Initialize Satellite Orbit_specification
        if not isinstance(orbit_n, Orbit_specification) and isinstance(orbit_n, list):
            if len(orbit_n) >= 6 and len(orbit_n) <= 7 and all(isinstance(x, int | float | datetime) for x in orbit_n):
                # Orbit_specification is initialized with new orbital parameters
                self.orbit_n = Orbit_specification(*orbit_n)
            elif len(orbit_n) < 6:
                print(
                    "Insuffizient data to specify Orbit_specification of satellite: ",
                    self.satName,
                )
        elif orbit_n is None:
            print("Orbit_specification of satellite: ", self.satName, " is not specified")
            self.orbit_n = None
        elif isinstance(orbit_n, Orbit_specification):
            # Orbit_specification object is passed
            self.orbit_n = orbit_n
        else:
            raise ValueError(
                "Invalid Orbit_specification object provided for satellite: ",
                self.satName,
            )

        # Calculate TLE file path if there is a valid Orbit and a valid epoch
        if self.orbit_n is not None:
            if self.orbit_n.epoch_str is not None:
                self.write_tle_file()
                lines = self.tle_str.splitlines()
                # Extract the variables
                satellite_name = lines[0]  # First line is the satellite name
                line_1 = lines[1]  # Second line is TLE line 1
                line_2 = lines[2]  # Third line is TLE line 2
                self.skf = EarthSatellite(line_1, line_2, satellite_name)
            else:
                print(
                    "Warning: Orbit_specification epoch is not specified for satellite: ",
                    self.satName,
                    " To generate the skyfield satellite object, specify the epoch.",
                )
