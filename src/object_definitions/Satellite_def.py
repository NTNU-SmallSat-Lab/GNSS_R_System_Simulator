from skyfield.api      import load, wgs84

class Satellite:
    def __init__(self, satID, orbit_n=None, satName=None, tle_file_path=None, satNo_in_tle=0):
        """
        =========================================================================================================
        Satellite class:
            - A satellite object that contains satellite data.
            - Initialized with the following parameters (REQUIRED):
              -> Satellite ID: Unique identifier for the satellite                        [int]
            - Initialized with the following parameters (OPTIONAL):
              -> Orbit_specification:         Orbit_specification object containing the satellite's orbital data (Orbit_specification) (optional)
              -> sensors:       List of sensors on the satellite (list)                                     TODO
              -> battery:       Battery object containing the satellite's battery data (Battery)            TODO
              -> solarArray:    Solar array object containing the satellite's solar array data (SolarArray) TODO
              -> tle_file_path: Path to the TLE file (str) (optional)
                [Only available if Satellite was initialized with an Orbit_specification object]
            - Satellite class variables (CALCULATED):
              -> tle_file_path: Path to the TLE file (str) [saved in "autogenerated" folder with Sat-ID as filename]

              -> skf:       Skyfield satellite object (Skyfield satellite)
                                  [calculated with TLE file, directly if this class was initialized with
                                   a TLE file, or indirectly if initialized with an Orbit_specification
                                   object, and the TLE file was generated]
        =========================================================================================================
        """
        # If tle-file is provided, initialize the satellite with the TLE data
        if tle_file_path is not None:
            if not os.path.exists(tle_file_path):
                raise FileNotFoundError(f"TLE file not found: {tle_file_path}")
            if orbit_n is not None:
                raise ValueError("Cannot initialize Satellite with both TLE file and Orbit_specification object")
            print(f"Initializing Satellite with TLE file: {tle_file_path}")
            self.__initWithTLE(tle_file_path, satNo_in_tle, satName)
        else:
            # Initialize satellite with Orbit_specification object
            print(f"Initializing Satellite with Orbit_specification object")
            self.__initWithOrbit(satID, orbit_n, satName)

        self.sensors        = []
        self.battery        = []
        self.solarArray     = []
    """
    =========================================================================================================
    Setter functions
    =========================================================================================================
    """
    def set_classification(self, classification) -> None:
        """Set the classification of the satellite."""
        if classification not in ['U', 'C', 'S']:
            raise ValueError("Invalid classification")
        self.classification = classification

    def set_orbit(self, orbit_n) -> None:
        """Set the orbit_n of the satellite."""
        if isinstance(orbit_n, Orbit_specification):
            self.orbit_n = orbit_n
        elif isinstance(orbit_n, list):
            if len(orbit_n) == 6:
                # Orbit_specification is initialized with new orbital parameters
                self.orbit_n = Orbit_specification(*orbit_n)
            elif len(orbit_n) < 6:
                print("Insuffizient data to specify Orbit_specification of satellite: ", self.satName)
        else:
            raise ValueError("Invalid Orbit_specification object provided for satellite: ", self.satName)
    
    def set_epoch(self, epoch) -> None:
        """Set the epoch of the satellite."""
        if self.orbit_n is None:
            print("Warning: Orbit_specification is not specified for this satellite. Cannot set epoch.")
            return
        self.orbit_n.set_start_time(epoch)

        # Generate TLE file if it does not exist and generate the skyfield satellite object
        if not self.tle_exists():
            self.write_tle_file()
            self.skf = load.tle_file(self.tle_file_path)[0]
    """
    =========================================================================================================
    Getter functions
    =========================================================================================================
    """
    def get_TLE(self)                            -> str:
        """Get the TLE path if it exists."""
        if self.tle_exists():
            return self.tle_file_path
        else:
            print("Warning: TLE has not yet been generated")
            return None

    def get_orbit(self)                          -> Orbit_specification:
        # Extract orbit_n from the satellit object
        return self.orbit_n

    def tle_exists(self)                         -> bool:
        """Check if the TLE file exists."""
        return self.tle_file_path is not None

    def write_tle_file(self)                     -> str:   
        """
        =========================================================================
        Write the TLE object passed in "tle_str" to a file
            and return the path to the file in path_TLE
        =========================================================================
        """
        tle_str = ReadWriteSatData.generate_tle_data_string(self)
        if tle_str is None:
            print("TLE DATA CANNOT BE GENERATED FOR SATELLITE: ", self.satID)
            return None

        filePath  = os.path.join(Constants.tle_eph_folder_path, self.satName+ ".tle")

        # Make sure the directory exists
        if not os.path.exists(Constants.tle_eph_folder_path):
            print(f"Creating directory: {Constants.tle_eph_folder_path}")
            os.makedirs(Constants.tle_eph_folder_path)

        # Check if the file already exists
        if os.path.exists(filePath):
            print(f"Warning: TLE file already exists for {self.satID} \n-- Overwriting previous TLE file --")
            # delete the file
            os.remove(filePath)

        # Write the TLE to the file
        try:
            with open(filePath, 'w') as file:
                file.write(tle_str)
            self.tle_file_path = filePath
            print(f"TLE written to {filePath}")
        except IOError:
            print(f"Warning: TLE file could not be written for {self.satID}")
        return filePath

    def propagate_orbit(self, startTime, duration, deltaT) -> np.array:
        """
        =========================================================================
        Propagate the satellite orbit for a given duration and a given time step 
        =    startTime:  Start time of the propagation   [datetime]             =
        =    duration:   Duration of the propagation     [seconds]              =
        =    deltaT:     Time step for the propagation   [seconds]              =
        =    return:     Position and velocity of the satellite at each time    =
        =    -> This function used "Skyfield" to propagate the satellite orbit  =
        =                                                                       =
        =    self.position (propagated position)                                = 
        =    self.velocity (propagated velocity)                                =
        =========================================================================
        """
        times_i = []
        ts      = load.timescale()
        for t in range(0, duration, deltaT):
            times_i.append(ts.utc(startTime + timedelta(seconds=t)))

        position = np.array([self.skf.at(t).position.m       for t in times_i])
        velocity = np.array([self.skf.at(t).velocity.m_per_s for t in times_i])

        self.time_prop_vec   = times_i
        self.positions_eci   = np.transpose(position)
        self.velocities_eci  = np.transpose(velocity)

    def __initWithTLE(self, tle_file_path, satNo_in_tle, satName=None):
        """
        =========================================================================
        Initialize the satellite object with the TLE data from the file
        =========================================================================
        """
        sat_data_all = ReadWriteSatData.read_tle_data(tle_file_path)
        if sat_data_all is None:
            raise ValueError("Invalid TLE data")
        
        if (len(sat_data_all) > 1 and satName is None):
            print("Warning: Multiple satellites found in TLE file. Using the first satellite data only.     \n    => If all satellites should be initialized, use the SatelliteConfiguration class")

        if satName is not None:
            # Initialize one satellite from a TLE file only
            for sat_data_i in sat_data_all:
                if sat_data_i.satName == satName:
                    sat_data = sat_data_i
                    break
        else:
            # Initialize the first satellite from the TLE file
            sat_data = sat_data_all[0]

        # calculate semi major axis
        self.tle_file_path  = tle_file_path
        self.satID          = sat_data.satCatalogNumber
        self.satName        = sat_data.satName
        self.classification = sat_data.classification
        semi_major_axis     = (Constants.GM_earth_tt / (sat_data.meanMotion * 2 * pi / Constants.Sec_per_day) ** 2) ** (1/3)
        self.orbit_n        = Orbit_specification(sat_data.inclination, sat_data.eccentricity, sat_data.raan, sat_data.argOfPerigee, sat_data.meanAnomaly, semi_major_axis, sat_data.epoch)
        self.launch_year    = sat_data.launchYear # TODO as datetime object
        self.lauch_Noyear   = sat_data.lauchNoInYear
        self.lauch_piece    = sat_data.launchPiece
        self.meanMotion_1   = sat_data.firstDerMeanMotion
        self.meanMotion_2   = sat_data.secDerivMeanMotion
        self.B_star         = sat_data.B_star
        self.element_set_no = sat_data.ElementSetNo
        self.skf            = load.tle_file(tle_file_path)[satNo_in_tle]

