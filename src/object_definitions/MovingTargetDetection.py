        times_movingTarget = sorted(self.moving_target_object.timestamps)

        # Iterate through each satellite constellation
        for gnss_name, gnss_value in self.gnss_constellation.items():
            # Sort times in the reflection dictionary in ascending order
            sat_times = sorted(self.reflection_dict_time[gnss_name].keys())
            # Iterate through each time/"circle" in the moving target trajectory
            for pos_shape_i in tqdm(self.gdf_time_series.itertuples(), desc=f"Calculating coverage for {gnss_name}", unit="time", leave=False):
                # Calculate a "circle" around the ship position
                shape_circle = self._circle_for_traj_point(pos_shape_i.geometry)                  # TODO: this should be updated on a later stage (use antenna-gain and orbit height instead of grid_size_m)

                # Get the time of the moving target trajectory
                time_i = dt.datetime.strptime(pos_shape_i.datetime_s, '%Y-%m-%d %H:%M:%S').replace(tzinfo=dt.timezone.utc)

                # Instead of exact match, find keys within 1 second tolerance
                found_match    = False
                time_tolerance = dt.timedelta(seconds=1)

                for sat_time in times_sat:
                    if abs(sat_time - time_i) <= time_tolerance:
                        found_match   = True
                        matching_time = sat_time
