    def calculate_moving_target_reflection_intersection(self, sat_const=None, earth_model='spherical', max_refl_angle=45, verbose=False):
        """
        Calculate the intersection of the moving target trajectory with the reflection points.
    
        A moving target is considered "detected" if the reflection point is within the grid cell
        for a certain time
        """
        ########################################
        # Calculate all the reflection points  #
        ########################################
        # Get time series in UTC format for the satellite constellation
        times_sat             = [time.utc_datetime() for time in self.sat_constellation.times_skyfield]
        total_comp_refl       = 0
        reflection_dict       = {} # Dictionary to store the reflection points for each GNSS constellation
        for gnss_name, gnss_const in self.gnss_constellation.items():
            total_comp_refl += len(self.sat_constellation.satellites) * len(gnss_const.satellites)
        # Calculate all the reflection points for the sateellite constellations in use

        with tqdm(total=total_comp_refl, desc="Reflection calculations", unit="reflection") as pbar:
            for gnss_name, gnss_const in self.gnss_constellation.items():
                if verbose:
                    print('-----------------------------------------------------------------')
                    print(f'\nCalculating reflections for GNSS constellation \"{gnss_name}\"')
                reflections_vec = []

                for sat_no, sat in enumerate(self.sat_constellation.satellites):
                    # Update status but don't advance the progress bar yet
                    pbar.set_description(f"GNSS-R Sat-{sat_no + 1} with {gnss_name}")

                    for i, gnss_sat in enumerate(gnss_const.satellites):
                        if i % 5 == 0:
                            pbar.set_description(
                                f"GNSS-R Sat-{sat_no + 1} with {gnss_name} [{i}/{len(gnss_const.satellites)}]"
                            )
                        # Perform the reflection calculation
                        refl_gnss = Reflection(
                            gnss_sat.satID, sat.satID, 
                            earth_model=earth_model, angle=max_refl_angle, 
                            gnss_const=gnss_name
                        )
                        refl_gnss.compute_reflection_coordinates(gnss_sat, sat, times_sat)
                        reflections_vec.append(refl_gnss)

                        # Update progress bar after each reflection calculation
                        pbar.update(1)
                reflection_dict[gnss_const.satConfigName] = reflections_vec

        ######################################################
        # Resort reflections_dict to reflection_dict_time    #
        ######################################################
        for gnss_name, gnss_value in reflection_dict.items():
            # add the gnss_constallation name to reflection_dict_time
            self.reflection_dict_time[gnss_name] = {}
            # Create a dictionary to store the reflection points for each time
            # Iterate through each reflection object
            for refl_obj in reflection_dict[gnss_name]:
                # refl_obj contains all the reflection points for a gnss satellite and a gnss_r (leo) satellite
                time_vector_all_refl = refl_obj.time_vec
                # Check if the time is already in the dictionary
                for time_i in time_vector_all_refl:
                    if time_i not in self.reflection_dict_time[gnss_name]:
                        # If not, create a new list for this time
                        self.reflection_dict_time[gnss_name][time_i] = []
                    # Append the reflection object to the list for this time
                    self.reflection_dict_time[gnss_name][time_i].append(refl_obj)

        ######################################################
