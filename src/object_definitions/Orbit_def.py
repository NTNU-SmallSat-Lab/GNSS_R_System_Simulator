from datetime import datetime, timezone
import math
import numpy as np
from object_definitions.Constants_def  import Constants

class Orbit:
    def __init__(self, i, e, raan, p, M, a, epochTime=None) -> None:
        """
        =========================================================================================================
        Orbit class:
          - Defines an orbit object: Initialized with the following parameters:
            - Inclination                       (i)          [degrees]
            - Eccentricity                      (e)          [-]
            - Right Ascension of Ascending Node (RAAN)       [deg]
            - Argument of perigee               (p)          [deg]
            - Mean anomaly                      (M)          [deg]
            - Semi-major axis                   (a)          [m]
            - "start time of Orbit"             (dt_start)   [YYYY:MM:DD HH:mm:ss UTC] (optional)
        =========================================================================================================
        """
        # Check if enough variables are provided
        if any(var is None for var in [i, e, raan, p, M, a]):
#        if i is None or e is None or raan is None or p is None or M is None or a is None:
            raise ValueError("Orbit undefined, not sufficient variables provided")

        # Initialize orbit
        self.i         = i                                                                # Inclination in degrees
        self.e         = e                                                                # Eccentricity
        self.RAAN      = raan                                                             # Right Ascension of Ascending Node in degrees
        self.p         = p                                                                # Argument of perigee in degrees
        self.M         = M                                                                # Mean anomaly
        self.a         = a                                                                # Semi-major axis in m
        self.epoch     = self.conv_DateTime_to_Epoch(epochTime) if epochTime else None    # Eopch in YYDDD.DDDDDDDD format (TLE format)
        self.dt_start  = epochTime if epochTime else None                                 # Start time in datetime format
        self.n         = math.sqrt(Constants.GM_earth_tt / (self.a**3))                   # Mean motion in rad/s

    def conv_DateTime_to_Epoch(self, dt_epoch):
        # Convert datetime to TLE epoch format YYDDD.DDDDDDDD
        tle_year                 = dt_epoch.year % 100
        start_of_year            = datetime(dt_epoch.year, 1, 1, tzinfo=timezone.utc)
        days_since_start_of_year = (dt_epoch - start_of_year).total_seconds() / Constants.Sec_per_day

        # Format strings to TLE Epoch format
        epoch_year_str = f"{tle_year:02d}"
        epoch_days_str = f"{days_since_start_of_year:012.8f}"
        tle_epoch      = epoch_year_str + epoch_days_str
        return tle_epoch

    """
    =========================================================================================================
    Setter functions
    =========================================================================================================
    """
    def set_start_time(self, dt_start):
        # Set the start time of the orbit
        #Check if start time is [YYYY:MM:DD HH:mm:ss UTC] format
        if not isinstance(dt_start, datetime):
            raise ValueError("Invalid start time format. Please provide a datetime object")
        # Check if dt_start is timezone-aware and in UTC
        if dt_start.tzinfo is None or dt_start.tzinfo != timezone.utc:
            raise ValueError("Start time must be a timezone-aware datetime object in UTC")
        self.dt_start = dt_start
        self.epoch    = self.conv_DateTime_to_Epoch(dt_start)
    
    """
    =========================================================================================================
    Getter functions
    =========================================================================================================
    """
    @staticmethod
    def generate_satID():
        # Generate satellite ID based on files in the TLE directory
        import os
        full_path = os.path.join(Constants.tle_folderpath, "Autogenerated")
        tle_files = [f for f in os.listdir(full_path) if f.endswith('.tle')]
        
        # Generate a unique ID by counting files (example logic)
        satID = len(tle_files) + 1
        return satID
